/// crie para mim uma pagina de cadastrar usuário tendo um campo para colocar
/// marcar se é juridica, se for juridica abrir campo de razão social e cnpj,
/// se for fisica abrir nome, sobrenome, cpf, e os demais campos: email,
/// senha, telefone, whatsapp, cargo/função, registro profissional, seleção do
/// tipo de usuario sendo eles: operador, cliente, supervisor e administrador
/// e tbm a seleção se está ativo ou inativo, e botão de voltar pagina e
/// abaixo salvar ou cancelar.
