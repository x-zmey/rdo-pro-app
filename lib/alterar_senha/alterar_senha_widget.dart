  Future<void> _salvarSenha() async {
    final current = _model.textController1?.text ?? '';
    final nova = _model.textController2?.text ?? '';
    final confirma = _model.textController3?.text ?? '';

    if (current.trim().isEmpty) {
      ScaffoldMessenger.of(context).showSnackBar(
        const SnackBar(content: Text('Senha atual é obrigatória')),
      );
      return;
    }
    if (nova.trim().isEmpty) {
      ScaffoldMessenger.of(context).showSnackBar(
        const SnackBar(content: Text('Nova senha é obrigatória')),
      );
      return;
    }
    if (nova.length < 6) {
      ScaffoldMessenger.of(context).showSnackBar(
        const SnackBar(
          content: Text('A nova senha deve ter no mínimo 6 caracteres'),
        ),
      );
      return;
    }
    if (nova != confirma) {
      ScaffoldMessenger.of(context).showSnackBar(
        const SnackBar(
          content: Text('A confirmação da senha não corresponde'),
        ),
      );
      return;
    }

    final token = FFAppState().UserToken;
    if (token.isEmpty) {
      ScaffoldMessenger.of(context).showSnackBar(
        const SnackBar(
          content: Text('Sessão expirada. Faça login novamente.'),
        ),
      );
      return;
    }

    try {
      final res = await AtualizarSenhaCall.call(
        token: token,
        currentPassword: current,
        password: nova,
        passwordConfirmation: confirma,
      );
      if (!mounted) return;
      if (res.succeeded) {
        final msg = AtualizarSenhaCall.message(res.jsonBody) ??
            'Senha alterada com sucesso!';
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(content: Text(msg)),
        );
        _model.textController1?.clear();
        _model.textController2?.clear();
        _model.textController3?.clear();
        safeSetState(() {});
      } else {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(
            content: Text(_mensagemErroAlterarSenha(res.jsonBody)),
            backgroundColor: FlutterFlowTheme.of(context).error,
          ),
        );
      }
    } catch (e) {
      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(
            content: Text('Erro ao alterar senha: $e'),
            backgroundColor: FlutterFlowTheme.of(context).error,
          ),
        );
      }
    }
  }

